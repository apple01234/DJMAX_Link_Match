import "server-only";
import { AsyncLocalStorage } from "node:async_hooks";
import pg from "pg";

/**
 * Postgres(Neon) 접속. Vercel의 Neon 연동이 DATABASE_URL을 넣어 준다.
 * 서버리스 함수는 인스턴스가 여러 개 뜰 수 있으므로 상태는 전부 DB에 둔다.
 *
 * 무결성은 가능한 한 DB 제약으로 강제한다:
 *  - picks.pick_no PRIMARY KEY → 같은 차례에 두 번 지명 불가
 *  - picks.player_id UNIQUE   → 한 선수를 두 팀이 지명 불가
 *  - draft.id = 1 CHECK       → 드래프트 상태는 단일 행
 */
const SCHEMA = /* sql */ `
CREATE TABLE IF NOT EXISTS teams (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT    NOT NULL UNIQUE,
  captain       TEXT    NOT NULL,
  captain_code  TEXT    NOT NULL UNIQUE,
  color         TEXT    NOT NULL,
  created_at    BIGINT  NOT NULL
);

CREATE TABLE IF NOT EXISTS players (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nickname  TEXT    NOT NULL UNIQUE,
  tier      TEXT    NOT NULL DEFAULT 'BG' CHECK (tier IN ('GM','M','DM','PT','GD','SV','BR','IR','AM','BG')),
  rating    INTEGER NOT NULL DEFAULT 0 CHECK (rating >= 0),
  main_key  TEXT    NOT NULL DEFAULT '4B' CHECK (main_key IN ('4B','5B','6B','8B')),
  note      TEXT    NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS picks (
  pick_no    INTEGER PRIMARY KEY,
  team_id    INTEGER NOT NULL REFERENCES teams(id)   ON DELETE CASCADE,
  player_id  INTEGER NOT NULL UNIQUE REFERENCES players(id) ON DELETE CASCADE,
  auto       BOOLEAN NOT NULL DEFAULT FALSE,
  picked_at  BIGINT  NOT NULL
);

CREATE TABLE IF NOT EXISTS draft (
  id               INTEGER PRIMARY KEY CHECK (id = 1),
  status           TEXT    NOT NULL DEFAULT 'setup'
                   CHECK (status IN ('setup','running','paused','done')),
  rounds           INTEGER NOT NULL DEFAULT 3 CHECK (rounds BETWEEN 1 AND 10),
  pick_seconds     INTEGER NOT NULL DEFAULT 60 CHECK (pick_seconds BETWEEN 10 AND 600),
  order_json       TEXT    NOT NULL DEFAULT '[]',
  turn_started_at  BIGINT,
  paused_left_ms   BIGINT,
  version          INTEGER NOT NULL DEFAULT 0
);

-- 대입 제한 카운터. 인스턴스가 여러 개여도 같은 값을 보도록 DB에 둔다.
CREATE TABLE IF NOT EXISTS rate_limits (
  key       TEXT   PRIMARY KEY,
  count     INTEGER NOT NULL,
  reset_at  BIGINT NOT NULL
);

INSERT INTO draft (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- 2026-11: 티어를 S/A/B/C에서 V-ARCHIVE 티어 그룹으로 바꾼다. 옛 제약이 남아 있을 때 한 번만 실행되고,
-- 기존 선수의 티어는 레이팅으로 다시 매긴다 (기준 점수는 types.ts TIER_INFO와 같다).
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint
             WHERE conname = 'players_tier_check' AND pg_get_constraintdef(oid) LIKE '%''S''%') THEN
    ALTER TABLE players DROP CONSTRAINT players_tier_check;
    UPDATE players SET tier = CASE
      WHEN rating >= 9950 THEN 'GM' WHEN rating >= 9700 THEN 'M'  WHEN rating >= 9000 THEN 'DM'
      WHEN rating >= 8200 THEN 'PT' WHEN rating >= 7400 THEN 'GD' WHEN rating >= 6600 THEN 'SV'
      WHEN rating >= 5300 THEN 'BR' WHEN rating >= 4000 THEN 'IR' WHEN rating >= 500  THEN 'AM'
      ELSE 'BG' END;
    ALTER TABLE players ADD CONSTRAINT players_tier_check
      CHECK (tier IN ('GM','M','DM','PT','GD','SV','BR','IR','AM','BG'));
    ALTER TABLE players ALTER COLUMN tier SET DEFAULT 'BG';
  END IF;
END $$;
`;

// BIGINT(epoch ms)를 문자열이 아닌 number로 받는다 (2^53 안쪽 값만 쓴다)
pg.types.setTypeParser(pg.types.builtins.INT8, (v) => Number(v));

declare global {
  // dev 서버 HMR 시 풀이 중복 생성되지 않도록 전역에 보관
  var __linkmatchPool: { pool: pg.Pool; ready: Promise<void> } | undefined;
}

function connectionString(): string {
  // Vercel 미리보기 배포는 운영 DB를 절대 쓰지 않는다. Neon 연동이 Preview에도 DATABASE_URL을 넣어 주므로,
  // 미리보기에서는 전용 브랜치 주소(PREVIEW_DATABASE_URL)만 쓰고, 없으면 운영 DB로 넘어가지 않고 멈춘다.
  if (process.env.VERCEL_ENV === "preview") {
    const preview = process.env.PREVIEW_DATABASE_URL;
    if (!preview) throw new Error("미리보기 배포에 PREVIEW_DATABASE_URL이 없습니다. 운영 DB는 쓰지 않습니다.");
    return strictSsl(preview);
  }
  const url = process.env.DATABASE_URL || process.env.POSTGRES_URL;
  if (!url) throw new Error("DATABASE_URL이 설정되지 않았습니다. (.env.example 참고)");
  return strictSsl(url);
}

/**
 * pg 8은 sslmode=require를 verify-full(인증서·호스트 검증)로 취급하며 경고를 낸다.
 * pg 9부터는 검증하지 않는 libpq 의미로 바뀌므로, 지금 동작을 명시해 업그레이드해도 약해지지 않게 한다.
 */
export function strictSsl(url: string): string {
  return url.replace(/([?&]sslmode=)(prefer|require|verify-ca)\b/, "$1verify-full");
}

function pool(): { pool: pg.Pool; ready: Promise<void> } {
  if (!globalThis.__linkmatchPool) {
    // 서버리스 인스턴스 하나가 동시에 쓰는 연결은 적다. Neon은 -pooler 주소(PgBouncer)를 쓰면 된다.
    const p = new pg.Pool({ connectionString: connectionString(), max: 5, idleTimeoutMillis: 10_000 });
    const ready = p.query(SCHEMA).then(() => undefined);
    ready.catch(() => {
      globalThis.__linkmatchPool = undefined; // 다음 요청에서 다시 시도
    });
    globalThis.__linkmatchPool = { pool: p, ready };
  }
  return globalThis.__linkmatchPool;
}

type Queryable = Pick<pg.PoolClient, "query">;
const txClient = new AsyncLocalStorage<Queryable>();

/** 트랜잭션 안이면 그 연결로, 아니면 풀에서 실행한다. */
async function exec(sql: string, params: unknown[]): Promise<pg.QueryResult> {
  const inTx = txClient.getStore();
  if (inTx) return inTx.query(sql, params);
  const { pool: p, ready } = pool();
  await ready;
  return p.query(sql, params);
}

export async function all<T>(sql: string, ...params: unknown[]): Promise<T[]> {
  return (await exec(sql, params)).rows as T[];
}

export async function get<T>(sql: string, ...params: unknown[]): Promise<T | undefined> {
  return (await exec(sql, params)).rows[0] as T | undefined;
}

export async function run(sql: string, ...params: unknown[]): Promise<void> {
  await exec(sql, params);
}

/**
 * 드래프트 행을 FOR UPDATE로 잠근 뒤 실행한다. 모든 쓰기가 이 잠금을 거치므로
 * SQLite의 BEGIN IMMEDIATE처럼 '읽고-검사하고-쓰기'가 한 번에 하나씩 처리된다.
 */
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (txClient.getStore()) return fn(); // 이미 트랜잭션 안
  const { pool: p, ready } = pool();
  await ready;
  const client = await p.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT 1 FROM draft WHERE id = 1 FOR UPDATE");
    const result = await txClient.run(client, fn);
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

/** 트랜잭션 밖에서 쓰는 단발성 쿼리용 (대입 제한 카운터 등) */
export const query = exec;
